const { Router } = require('express');
const controller = require('./admin.controller');
const administratorController = require('./administrator.controller');
const { requireAuth, requireRole } = require('../../middlewares/auth.middleware');
const notificationsController = require('../notifications/notifications.controller');
const orderController = require('../orders/order.controller');
const adminBannerController = require('../banners/admin_banner.controller');

const router = Router();
router.use(requireAuth, requireRole('admin'));
router.get('/dashboard', controller.dashboard);
router.get('/reviews', controller.productReviews);
router.delete('/reviews/:id', controller.deleteProductReview);
router.get('/customers', controller.customers);
router.get('/customers/:id', controller.customerDetails);
router.get('/administrators', administratorController.listAdministrators);
router.post('/administrators', administratorController.createAdministrator);
router.patch('/administrators/:id', administratorController.updateAdministrator);
router.post('/products/image', controller.uploadProductImage);
router.get('/banners', adminBannerController.list);
router.get('/banners/:id', adminBannerController.detail);
router.post('/banners', adminBannerController.create);
router.patch('/banners/:id', adminBannerController.update);
router.delete('/banners/:id', adminBannerController.remove);
router.post('/banners/image', adminBannerController.receiveImages, adminBannerController.uploadImage);
router.get('/orders', orderController.adminList);
router.get('/orders/:id', orderController.adminDetail);
router.post('/orders/:id/accept', orderController.adminAccept);
router.post('/orders/:id/reject', orderController.adminReject);
router.patch('/orders/:id/status', orderController.adminUpdateStatus);
router.get('/notifications', notificationsController.adminList);
router.post('/notifications', notificationsController.adminCreate);
router.patch('/notifications/:id/archive', notificationsController.adminArchive);

module.exports = router;
