function makeToken() {
  return crypto.randomBytes(64).toString('hex');
}

function normalizeTimestamp(value) {
  return value == null ? null : new Date(value).toISOString();
}

async function createFixture(pool) {
  await pool.query(`
    CREATE TABLE users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      full_name VARCHAR(150) NOT NULL,
      phone VARCHAR(20) NOT NULL UNIQUE,
      email VARCHAR(150) UNIQUE,
      password_hash TEXT NOT NULL,
      role VARCHAR(20) NOT NULL DEFAULT 'customer',
      is_active BOOLEAN NOT NULL DEFAULT true
    );

    CREATE TABLE user_sessions (
      id UUID PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
      revoked_at TIMESTAMPTZ,
      expires_at TIMESTAMPTZ NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE INDEX idx_user_sessions_user_id ON user_sessions (user_id);

    CREATE TABLE refresh_tokens (
      id SERIAL PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
      token_hash TEXT NOT NULL UNIQUE,
      user_agent TEXT,
      ip_address VARCHAR(45),
      expires_at TIMESTAMPTZ NOT NULL,
      revoked_at TIMESTAMPTZ,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      session_id UUID,
      CONSTRAINT refresh_tokens_session_id_fkey
        FOREIGN KEY (session_id) REFERENCES user_sessions (id) ON DELETE CASCADE
    );

    CREATE INDEX idx_refresh_tokens_user_id ON refresh_tokens (user_id);
    CREATE INDEX idx_refresh_tokens_session_id ON refresh_tokens (session_id);
  `);

  const users = await pool.query(
    `INSERT INTO users (full_name, phone, email, password_hash, role)
     VALUES
       ('Migration Test Customer', '+258870000001', 'migration-customer@example.test', 'not-used', 'customer'),
       ('Migration Test Admin', '+258870000002', 'migration-admin@example.test', 'not-used', 'admin')
     RETURNING id, role`
  );
  const customer = users.rows.find((user) => user.role === 'customer');
  const admin = users.rows.find((user) => user.role === 'admin');
  const future = new Date(Date.now() + 60 * 60 * 1000);
  const past = new Date(Date.now() - 60 * 60 * 1000);
  const createdAt = new Date(Date.now() - 10 * 60 * 1000);
  const records = [];

  async function addToken({
    user,
    token = makeToken(),
    expiresAt = future,
    revokedAt = null,
    created = createdAt,
    sessionId = null,
    userAgent = `migration-test-${records.length}`,
    ipAddress = '192.0.2.19',
  }) {
    const result = await pool.query(
      `INSERT INTO refresh_tokens
         (user_id, token_hash, user_agent, ip_address, expires_at,
          revoked_at, created_at, session_id)
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
       RETURNING id, user_id, token_hash, user_agent, ip_address, expires_at,
                 revoked_at, created_at, session_id`,
      [
        user.id,
        require('../src/utils/tokens').hashRefreshToken(token),
        userAgent,
        ipAddress,
        expiresAt,
        revokedAt,
        created,
        sessionId,
      ]
    );
    const record = { ...result.rows[0], token, role: user.role };
    records.push(record);
    return record;
  }

  const existingSessionId = crypto.randomUUID();
  const existingSession = await pool.query(
    `INSERT INTO user_sessions (id, user_id, expires_at, created_at)
     VALUES ($1, $2, $3, $4)
     RETURNING id, user_id, expires_at, revoked_at, created_at`,
    [existingSessionId, customer.id, future, createdAt]
  );

  const activeCustomer = await addToken({ user: customer });
  const secondActiveCustomer = await addToken({ user: customer });
  const revokedCustomer = await addToken({
    user: customer,
    revokedAt: createdAt,
  });
  const expiredCustomer = await addToken({
    user: customer,
    expiresAt: past,
  });
  const activeAdmin = await addToken({ user: admin });
  const mappedRevoked = await addToken({
    user: customer,
    revokedAt: createdAt,
    sessionId: existingSessionId,
  });
  const mappedActive = await addToken({
    user: customer,
    sessionId: existingSessionId,
  });

  return {
    customer,
    admin,
    records,
    existingSessionId,
    existingSession: existingSession.rows[0],
    activeCustomer,
    secondActiveCustomer,
    revokedCustomer,
    expiredCustomer,
    activeAdmin,
    mappedRevoked,
    mappedActive,
  };
}

async function readOriginalTokenRows(pool) {
  const { rows } = await pool.query(
    `SELECT id, user_id, token_hash, user_agent, ip_address, expires_at,
            revoked_at, created_at, session_id
     FROM refresh_tokens ORDER BY id`
  );
  return rows.map((row) => ({
    ...row,
    expires_at: normalizeTimestamp(row.expires_at),
    revoked_at: normalizeTimestamp(row.revoked_at),
    created_at: normalizeTimestamp(row.created_at),
  }));
}

async function assertBackfill(pool, originalRows) {
  const { rows } = await pool.query(
    `SELECT rt.id, rt.user_id, rt.token_hash, rt.user_agent, rt.ip_address,
            rt.expires_at, rt.revoked_at, rt.created_at, rt.session_id,
            s.user_id AS session_user_id, s.expires_at AS session_expires_at,
            s.revoked_at AS session_revoked_at, s.created_at AS session_created_at
     FROM refresh_tokens rt
     LEFT JOIN user_sessions s ON s.id = rt.session_id
     ORDER BY rt.id`
  );

  assert.equal(rows.length, originalRows.length, 'refresh-token count is preserved');
  assert.ok(rows.every((row) => row.session_id), 'all tokens receive a session');
  assert.ok(
    rows.every((row) => row.session_user_id === row.user_id),
    'every token is linked to a session owned by the same user'
  );
  assert.ok(
    rows.every((row) => row.session_id !== null),
    'no refresh token has a null session link'
  );

  const originalById = new Map(originalRows.map((row) => [row.id, row]));
  for (const row of rows) {
    const original = originalById.get(row.id);
    assert.ok(original, `token ${row.id} remains present`);
    for (const field of [
      'user_id',
      'token_hash',
      'user_agent',
      'ip_address',
      'expires_at',
      'revoked_at',
      'created_at',
    ]) {
      const actual = field.endsWith('_at')
        ? normalizeTimestamp(row[field])
        : row[field];
      assert.equal(actual, original[field], `token ${row.id} preserves ${field}`);
    }

    if (original.session_id) {
      assert.equal(row.session_id, original.session_id);
    } else {
      assert.equal(
        normalizeTimestamp(row.session_expires_at),
        original.expires_at,
        `token ${row.id} copies its expiry to the new session`
      );
      assert.equal(
        normalizeTimestamp(row.session_revoked_at),
        original.revoked_at,
        `token ${row.id} copies its revocation state`
      );
      assert.equal(
        normalizeTimestamp(row.session_created_at),
        original.created_at,
        `token ${row.id} copies its creation time`
      );
    }
  }

  const { rows: orphanRows } = await pool.query(
    `SELECT count(*)::int AS count
     FROM refresh_tokens rt
     LEFT JOIN user_sessions s ON s.id = rt.session_id
     WHERE s.id IS NULL`
  );
  assert.equal(orphanRows[0].count, 0, 'there are no orphaned session links');

  const { rows: nullableColumn } = await pool.query(
    `SELECT is_nullable FROM information_schema.columns
     WHERE table_schema = current_schema()
       AND table_name = 'refresh_tokens' AND column_name = 'session_id'`
  );
  assert.equal(nullableColumn[0]?.is_nullable, 'NO');

  const { rows: revokedRows } = await pool.query(
    `SELECT count(*)::int AS count FROM refresh_tokens
     WHERE revoked_at IS NOT NULL`
  );
  assert.equal(
    revokedRows[0].count,
    originalRows.filter((row) => row.revoked_at !== null).length,
    'revoked tokens remain revoked'
  );

  const { rows: expiredRows } = await pool.query(
    `SELECT count(*)::int AS count FROM refresh_tokens WHERE expires_at <= now()`
  );
  assert.equal(
    expiredRows[0].count,
    originalRows.filter((row) => new Date(row.expires_at) <= new Date()).length,
    'expired tokens remain expired'
  );

  const { rows: compositeForeignKey } = await pool.query(
    `SELECT pg_get_constraintdef(oid) AS definition FROM pg_constraint
     WHERE conname = 'refresh_tokens_session_user_fkey'
       AND conrelid = 'refresh_tokens'::regclass`
  );
  assert.match(compositeForeignKey[0]?.definition ?? '', /FOREIGN KEY \(session_id, user_id\)/);
}

test('019 migrates legacy refresh tokens transactionally and preserves session compatibility', async (t) => {
  assertIsolatedTestDatabase();

  const controlPool = new Pool({
    ...env.db,
    options: '-c search_path=public',
  });
  let scopedPool;
  let schema;
  let previousPgOptions;
  let temporaryMigrationsDir;
  let server;

  try {
    await assertConnectedTestDatabase(controlPool);
    schema = `migration_019_${crypto.randomUUID().replaceAll('-', '')}`;
    await controlPool.query(`CREATE SCHEMA ${schema}`);
    await controlPool.end();

    previousPgOptions = process.env.PGOPTIONS;
    process.env.PGOPTIONS = `-c search_path=${schema}`;

    scopedPool = require('../src/config/db').pool;
    await assertConnectedTestDatabase(scopedPool);
    const fixture = await createFixture(scopedPool);

    await scopedPool.query(`
      CREATE TABLE schema_migrations (
        filename TEXT PRIMARY KEY,
        applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
      )
    `);
    const priorMigrations = discoverMigrations(MIGRATIONS_DIR).filter(
      (filename) => filename < MIGRATION_FILENAME
    );
    await scopedPool.query(
      `INSERT INTO schema_migrations (filename)
       SELECT unnest($1::text[]) ON CONFLICT (filename) DO NOTHING`,
      [priorMigrations]
    );

    const originalRows = await readOriginalTokenRows(scopedPool);
    const migrationSql = fs.readFileSync(
      path.join(MIGRATIONS_DIR, MIGRATION_FILENAME),
      'utf8'
    );

    temporaryMigrationsDir = fs.mkdtempSync(
      path.join(os.tmpdir(), 'virtualshop-migration-019-failure-')
    );
    fs.writeFileSync(
      path.join(temporaryMigrationsDir, MIGRATION_FILENAME),
      `${migrationSql}\nSELECT 1 / 0;\n`
    );

    await assert.rejects(
      runMigrations({
        pool: scopedPool,
        migrationsDir: temporaryMigrationsDir,
        args: ['--only', MIGRATION_FILENAME],
        logger: { log() {}, error() {} },
      }),
      /division by zero/
    );

    const afterFailure = await readOriginalTokenRows(scopedPool);
    assert.deepEqual(afterFailure, originalRows, 'failed backfill is rolled back');
    const { rows: failedLinks } = await scopedPool.query(
      'SELECT count(*)::int AS count FROM refresh_tokens WHERE session_id IS NOT NULL'
    );
    assert.equal(failedLinks[0].count, 2, 'backfill links are rolled back');
    const { rows: failedIndex } = await scopedPool.query(
      `SELECT 1 FROM pg_indexes WHERE schemaname = current_schema()
       AND indexname = 'idx_refresh_tokens_one_active_per_session'`
    );
    assert.equal(failedIndex.length, 0, 'partial DDL is rolled back');
    const { rows: failedColumn } = await scopedPool.query(
      `SELECT is_nullable FROM information_schema.columns
       WHERE table_schema = current_schema()
         AND table_name = 'refresh_tokens' AND column_name = 'session_id'`
    );
    assert.equal(failedColumn[0]?.is_nullable, 'YES', 'NOT NULL DDL is rolled back');
    const { rows: failedConstraint } = await scopedPool.query(
      `SELECT 1 FROM pg_constraint WHERE conname = 'refresh_tokens_session_user_fkey'
       AND conrelid = 'refresh_tokens'::regclass`
    );
    assert.equal(failedConstraint.length, 0, 'partial foreign-key DDL is rolled back');
    const { rows: failedUniqueConstraint } = await scopedPool.query(
      `SELECT 1 FROM pg_constraint WHERE conname = 'user_sessions_id_user_id_unique'
       AND conrelid = 'user_sessions'::regclass`
    );
    assert.equal(failedUniqueConstraint.length, 0, 'partial session constraint is rolled back');
    const { rows: failedLedger } = await scopedPool.query(
      'SELECT 1 FROM schema_migrations WHERE filename = $1',
      [MIGRATION_FILENAME]
    );
    assert.equal(failedLedger.length, 0, 'failed migration is not recorded');

    const migrationResults = await runMigrations({
      pool: scopedPool,
      migrationsDir: MIGRATIONS_DIR,
      args: ['--only', MIGRATION_FILENAME],
      logger: { log() {}, error() {} },
    });
    assert.deepEqual(migrationResults, [{ filename: MIGRATION_FILENAME, applied: true }]);
    await assertBackfill(scopedPool, originalRows);

    const { rows: sessionCount } = await scopedPool.query(
      'SELECT count(*)::int AS count FROM user_sessions'
    );
    assert.equal(
      sessionCount[0].count,
      1 + originalRows.filter((row) => row.session_id === null).length,
      'one session is created for each unmapped token and the existing session is preserved'
    );

    const existingRows = await scopedPool.query(
      'SELECT session_id FROM refresh_tokens WHERE id = ANY($1::int[])',
      [[fixture.mappedRevoked.id, fixture.mappedActive.id]]
    );
    assert.ok(
      existingRows.rows.every((row) => row.session_id === fixture.existingSessionId),
      'tokens already linked retain their session'
    );
    const { rows: existingSessionAfter } = await scopedPool.query(
      `SELECT id, user_id, expires_at, revoked_at, created_at
       FROM user_sessions WHERE id = $1`,
      [fixture.existingSessionId]
    );
    assert.deepEqual(existingSessionAfter[0], fixture.existingSession);

    await assertIndexConstraints(scopedPool, fixture);
    const express = require('express');
    const { requireAuth } = require('../src/middlewares/auth.middleware');
    const compatibilityApp = express();
    compatibilityApp.get('/me', requireAuth, (req, res) => {
      res.json({ user: req.user });
    });
    server = compatibilityApp.listen(0, '127.0.0.1');
    await new Promise((resolve, reject) => {
      server.once('listening', resolve);
      server.once('error', reject);
    });
    await assertLegacyTokenCompatibility(scopedPool, fixture, server);

    const beforeRerun = await readOriginalTokenRows(scopedPool);
    const rerun = await runMigrations({
      pool: scopedPool,
      migrationsDir: MIGRATIONS_DIR,
      args: ['--only', MIGRATION_FILENAME],
      logger: { log() {}, error() {} },
    });
    assert.deepEqual(rerun, [{ filename: MIGRATION_FILENAME, applied: false }]);
    assert.deepEqual(
      await readOriginalTokenRows(scopedPool),
      beforeRerun,
      'runner skips a migration already recorded without changing token rows'
    );

    const { rows: ledger } = await scopedPool.query(
      'SELECT count(*)::int AS count FROM schema_migrations WHERE filename = $1',
      [MIGRATION_FILENAME]
    );
    assert.equal(ledger[0].count, 1, 'runner records the migration exactly once');
  } finally {
    if (server) {
      await new Promise((resolve) => server.close(resolve));
    }
    if (scopedPool) await scopedPool.end();
    if (controlPool.totalCount || !controlPool.ended) {
      await controlPool.end();
    }
    if (temporaryMigrationsDir) {
      fs.rmSync(temporaryMigrationsDir, { recursive: true, force: true });
    }
    if (previousPgOptions === undefined) delete process.env.PGOPTIONS;
    else process.env.PGOPTIONS = previousPgOptions;

    if (schema) {
      const cleanupPool = new Pool({
        ...env.db,
        options: '-c search_path=public',
      });
      try {
        await cleanupPool.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
      } finally {
        await cleanupPool.end();
      }
    }
  }
});

async function assertIndexConstraints(pool, fixture) {
  const { rows: indexRows } = await pool.query(
    `SELECT indexdef FROM pg_indexes WHERE schemaname = current_schema()
     AND indexname = 'idx_refresh_tokens_one_active_per_session'`
  );
  assert.match(indexRows[0]?.indexdef ?? '', /UNIQUE INDEX/);
  assert.match(indexRows[0]?.indexdef ?? '', /WHERE \(revoked_at IS NULL\)/);

  const token = makeToken();
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('SAVEPOINT duplicate_active_probe');
    const duplicateActiveError = await client
      .query(
        `INSERT INTO refresh_tokens
           (user_id, token_hash, expires_at, session_id)
         VALUES ($1, $2, now() + interval '1 hour', $3)`,
        [
          fixture.mappedActive.user_id,
          require('../src/utils/tokens').hashRefreshToken(token),
          fixture.existingSessionId,
        ]
      )
      .then(
        () => null,
        (error) => error
      );
    assert.equal(
      duplicateActiveError?.code,
      '23505',
      `expected a unique violation, received ${duplicateActiveError?.code ?? 'no error'}`
    );
    await client.query('ROLLBACK TO SAVEPOINT duplicate_active_probe');
    const foreignKeySessionId = crypto.randomUUID();
    await client.query(
      `INSERT INTO user_sessions (id, user_id, expires_at)
       VALUES ($1, $2, now() + interval '1 hour')`,
      [foreignKeySessionId, fixture.admin.id]
    );
    await client.query('SAVEPOINT wrong_owner_probe');
    const wrongOwnerError = await client
      .query(
        `INSERT INTO refresh_tokens
           (user_id, token_hash, expires_at, session_id)
         VALUES ($1, $2, now() + interval '1 hour', $3)`,
        [
          fixture.customer.id,
          require('../src/utils/tokens').hashRefreshToken(makeToken()),
          foreignKeySessionId,
        ]
      )
      .then(
        () => null,
        (error) => error
      );
    assert.equal(
      wrongOwnerError?.code,
      '23503',
      `expected a foreign-key violation, received ${wrongOwnerError?.code ?? 'no error'}`
    );
    await client.query('ROLLBACK TO SAVEPOINT wrong_owner_probe');
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

async function assertLegacyTokenCompatibility(pool, fixture, server) {
  const authService = require('../src/modules/auth/auth.service');
  const {
    generateAccessToken,
    hashRefreshToken,
  } = require('../src/utils/tokens');
  const jwt = require('jsonwebtoken');

  const me = async (token) => fetch(
    `http://127.0.0.1:${server.address().port}/me`,
    { headers: { Authorization: `Bearer ${token}` } }
  );

  const activeLegacy = fixture.activeCustomer;
  const activeId = (
    await pool.query('SELECT id, session_id FROM refresh_tokens WHERE token_hash = $1', [
      activeLegacy.token_hash,
    ])
  ).rows[0];
  const legacyAccess = generateAccessToken(fixture.customer, activeId.id);
  assert.equal((await me(legacyAccess)).status, 200, 'legacy numeric sid resolves after backfill');

  const refreshed = await authService.refresh(activeLegacy.token, {});
  assert.equal(jwt.decode(refreshed.accessToken).sid, activeId.session_id);
  assert.notEqual(refreshed.refreshToken, activeLegacy.token);

  const revoked = await pool.query(
    'SELECT token_hash FROM refresh_tokens WHERE id = $1',
    [fixture.revokedCustomer.id]
  );
  await assert.rejects(
    authService.refresh(fixture.revokedCustomer.token, {}),
    (error) => error.statusCode === 401
  );
  assert.equal(
    revoked.rows[0].token_hash,
    hashRefreshToken(fixture.revokedCustomer.token),
    'revoked legacy refresh token remains hashed and rejected'
  );

  await assert.rejects(
    authService.refresh(fixture.expiredCustomer.token, {}),
    (error) => error.statusCode === 401
  );

  const adminToken = fixture.activeAdmin;
  const adminRow = (
    await pool.query('SELECT id FROM refresh_tokens WHERE token_hash = $1', [
      adminToken.token_hash,
    ])
  ).rows[0];
  const adminAccess = generateAccessToken(fixture.admin, adminRow.id);
  assert.equal((await me(adminAccess)).status, 200, 'legacy admin access token resolves');
  await authService.logout(adminToken.token);
  assert.equal((await me(adminAccess)).status, 401, 'logout revokes the associated session');
  await assert.rejects(
    authService.refresh(adminToken.token, {}),
    (error) => error.statusCode === 401
  );
}
